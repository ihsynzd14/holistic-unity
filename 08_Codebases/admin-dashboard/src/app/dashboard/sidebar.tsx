export default function Sidebar({ userId, userEmail }: { userId: string; userEmail: string }) {
  const pathname = usePathname();
  const router = useRouter();

  // Bind Sentry user context to this opaque UUID for the duration of
  // the dashboard session. The PII scrub in src/lib/sentry/scrub.ts
  // also reduces user objects to `{ id }` — this just sets the id
  // early so events captured BEFORE the scrub still carry it. Cleared
  // on unmount so logout doesn't leak the id into the next user's
  // session on the same device.
  useEffect(() => {
    Sentry.setUser({ id: userId });
    return () => { Sentry.setUser(null); };
  }, [userId]);

  async function handleSignOut() {
    Sentry.setUser(null);
    const supabase = createClient();
    await supabase.auth.signOut();
    router.push("/login");
    router.refresh();
  }

  return (
    <aside className="flex h-full w-[260px] flex-col border-r border-berry/5 bg-white/60 backdrop-blur-sm">
      {/* Brand */}
      <div className="flex items-center gap-3 px-6 py-5">
        <Image
          src="/logo.png"
          alt="Holistic Unity"
          width={40}
          height={40}
          className="rounded-xl"
        />
        <div>
          <h2 className="font-[family-name:var(--font-display)] text-lg font-bold text-charcoal">Holistic Unity</h2>
          <p className="text-[11px] font-medium tracking-wide text-berry-muted">Admin Panel</p>
        </div>
      </div>

      {/* Divider */}
      <div className="mx-5 h-px bg-gradient-to-r from-transparent via-berry/10 to-transparent" />

      {/* Navigation */}
      <nav className="flex-1 space-y-0.5 px-3 py-4">
        {navItems.map((item) => {
          const isActive =
            item.href === "/dashboard"
              ? pathname === "/dashboard"
              : pathname.startsWith(item.href);

          return (
            <Link
              key={item.href}
              href={item.href}
              className={`flex items-center gap-3 rounded-xl px-3.5 py-2.5 text-[13px] font-medium transition-all duration-200 ${
                isActive
                  ? "bg-berry text-white shadow-md shadow-berry/15"
                  : "text-charcoal-light hover:bg-berry-subtle/50 hover:text-berry-dark"
              }`}
            >
              {item.icon}
              {item.label}
            </Link>
          );
        })}
      </nav>

      {/* Gold accent line */}
      <div className="mx-5 h-px bg-gradient-to-r from-transparent via-gold/30 to-transparent" />

      {/* User / Sign Out */}
      <div className="px-4 py-4">
        <div className="mb-2.5 truncate px-1 text-[11px] font-medium text-charcoal-muted">{userEmail}</div>
        <button
          onClick={handleSignOut}
          className="flex w-full items-center gap-2 rounded-xl px-3.5 py-2.5 text-[13px] font-medium text-charcoal-muted transition-all duration-200 hover:bg-error-light hover:text-error"
        >
          <svg className="h-4 w-4" fill="none" viewBox="0 0 24 24" strokeWidth={1.5} stroke="currentColor">
            <path strokeLinecap="round" strokeLinejoin="round" d="M15.75 9V5.25A2.25 2.25 0 0013.5 3h-6a2.25 2.25 0 00-2.25 2.25v13.5A2.25 2.25 0 007.5 21h6a2.25 2.25 0 002.25-2.25V15m3 0l3-3m0 0l-3-3m3 3H9" />
          </svg>
          Sign Out
        </button>
      </div>
    </aside>
  );
}
